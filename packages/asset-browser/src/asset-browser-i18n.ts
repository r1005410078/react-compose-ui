export function getAssetBrowserMessages(locale: ComposeLocale, format?: Formatter) {
  const messages = dictionary[locale]
  const value = <K extends keyof typeof messages>(
    key: K,
    id: string,
    variables?: Readonly<Record<string, string | number>>,
  ) => format?.(id, messages[key], variables) ?? replace(messages[key], variables)
  return {
    assets: value('assets', 'assetBrowser.assets'),
    tree: value('tree', 'assetBrowser.tree'),
    search: value('search', 'assetBrowser.search'),
    connect: value('connect', 'assetBrowser.connect'),
    unsupportedLocal: value('unsupportedLocal', 'assetBrowser.unsupportedLocal'),
    noProvider: value('noProvider', 'assetBrowser.noProvider'),
    newFile: value('newFile', 'assetBrowser.newFile'),
    newFolder: value('newFolder', 'assetBrowser.newFolder'),
    import: value('import', 'assetBrowser.import'),
    refresh: value('refresh', 'assetBrowser.refresh'),
    rename: value('rename', 'assetBrowser.rename'),
    delete: value('delete', 'assetBrowser.delete'),
    save: value('save', 'assetBrowser.save'),
    discard: value('discard', 'assetBrowser.discard'),
    cancel: value('cancel', 'assetBrowser.cancel'),
    reload: value('reload', 'assetBrowser.reload'),
    force: value('force', 'assetBrowser.force'),
    create: value('create', 'assetBrowser.create'),
    confirmDelete: value('confirmDelete', 'assetBrowser.confirmDelete'),
    deleteQuestion: (count: number) => value(
      'deleteQuestion',
      'assetBrowser.deleteQuestion',
      { count },
    ),
    dirtyTitle: value('dirtyTitle', 'assetBrowser.dirtyTitle'),
    dirtyQuestion: (name: string) => value(
      'dirtyQuestion',
      'assetBrowser.dirtyQuestion',
      { name },
    ),
    conflictTitle: value('conflictTitle', 'assetBrowser.conflictTitle'),
    conflictQuestion: value('conflictQuestion', 'assetBrowser.conflictQuestion'),
    selected: (count: number) => value('selected', 'assetBrowser.selected', { count }),
    loading: value('loading', 'assetBrowser.loading'),
    emptyFolder: value('emptyFolder', 'assetBrowser.emptyFolder'),
    error: (message: string) => value('error', 'assetBrowser.error', { message }),
    partial: (succeeded: number, failed: number) => value(
      'partial',
      'assetBrowser.partial',
      { succeeded, failed },
    ),
    size: value('size', 'assetBrowser.size'),
    modified: value('modified', 'assetBrowser.modified'),
    type: value('type', 'assetBrowser.type'),
    download: value('download', 'assetBrowser.download'),
    binary: value('binary', 'assetBrowser.binary'),
    splitter: value('splitter', 'assetBrowser.splitter'),
    name: value('name', 'assetBrowser.name'),
    close: value('close', 'assetBrowser.close'),
  }
}

function replace(template: string, variables?: Readonly<Record<string, string | number>>) {
  if (!variables) return template
  return template.replace(/\{([^}]+)\}/gu, (_, key: string) => String(variables[key] ?? `{${key}}`))
}

export type AssetBrowserMessages = ReturnType<typeof getAssetBrowserMessages>
