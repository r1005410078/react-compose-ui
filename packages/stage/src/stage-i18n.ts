export function getStageMessages(
  locale: ComposeLocale,
  formatMessage: FormatMessage = (_id, fallback) => fallback,
) {
  const messages = translations[locale]
  return {
    rulerOrigin: formatMessage('stage.rulerOrigin', messages.rulerOrigin),
    horizontalRuler: formatMessage('stage.horizontalRuler', messages.horizontalRuler),
    verticalRuler: formatMessage('stage.verticalRuler', messages.verticalRuler),
    editingOverlay: formatMessage('stage.editingOverlay', messages.editingOverlay),
    horizontalScrollbar: formatMessage(
      'stage.horizontalScrollbar',
      messages.horizontalScrollbar,
    ),
    verticalScrollbar: formatMessage(
      'stage.verticalScrollbar',
      messages.verticalScrollbar,
    ),
    createGuide: formatMessage('stage.createGuide', messages.createGuide),
    createGuides: formatMessage('stage.createGuides', messages.createGuides),
    moveGuide: formatMessage('stage.moveGuide', messages.moveGuide),
    deleteGuide: formatMessage('stage.deleteGuide', messages.deleteGuide),
    toggleGridSnap: formatMessage('stage.toggleGridSnap', messages.toggleGridSnap),
    toggleSmartSnap: formatMessage('stage.toggleSmartSnap', messages.toggleSmartSnap),
    copy: formatMessage('stage.copy', messages.copy),
    cut: formatMessage('stage.cut', messages.cut),
    paste: formatMessage('stage.paste', messages.paste),
    duplicate: formatMessage('stage.duplicate', messages.duplicate),
    layerOrder: formatMessage('stage.layerOrder', messages.layerOrder),
    layerOrderUnavailable: formatMessage(
      'stage.layerOrderUnavailable',
      messages.layerOrderUnavailable,
    ),
    bringForward: formatMessage('stage.bringForward', messages.bringForward),
    sendBackward: formatMessage('stage.sendBackward', messages.sendBackward),
    bringToFront: formatMessage('stage.bringToFront', messages.bringToFront),
    sendToBack: formatMessage('stage.sendToBack', messages.sendToBack),
    library: formatMessage('stage.library', messages.library),
    libraryContent: formatMessage('stage.libraryContent', messages.libraryContent),
    basicCategory: (count: number) => formatMessage(
      'stage.basicCategory',
      messages.basicCategory(count),
      { count },
    ),
    basicCategoryItems: formatMessage(
      'stage.basicCategoryItems',
      messages.basicCategoryItems,
    ),
    add: (label: string) => formatMessage(
      'stage.add',
      messages.add(label),
      { label },
    ),
    containerLabels: formatMessage('stage.containerLabels', messages.containerLabels),
    renameContainer: (name: string) => formatMessage(
      'stage.renameContainer',
      messages.renameContainer(name),
      { name },
    ),
    sceneActive: (name: string) => formatMessage(
      'stage.sceneActive',
      messages.sceneActive(name),
      { name },
    ),
    sceneInactive: (name: string) => formatMessage(
      'stage.sceneInactive',
      messages.sceneInactive(name),
      { name },
    ),
    scenePreview: (name: string) => formatMessage(
      'stage.scenePreview',
      messages.scenePreview(name),
      { name },
    ),
    setActiveScene: formatMessage('stage.setActiveScene', messages.setActiveScene),
    canvasActions: formatMessage('stage.canvasActions', messages.canvasActions),
    group: formatMessage('stage.group', messages.group),
    ungroup: formatMessage('stage.ungroup', messages.ungroup),
    createComponent: formatMessage('stage.createComponent', messages.createComponent),
    delete: formatMessage('stage.delete', messages.delete),
    viewMenu: formatMessage('stage.viewMenu', messages.viewMenu),
    toolsMenu: formatMessage('stage.toolsMenu', messages.toolsMenu),
    selectTool: formatMessage('stage.selectTool', messages.selectTool),
    panTool: formatMessage('stage.panTool', messages.panTool),
    gridSnap: formatMessage('stage.gridSnap', messages.gridSnap),
    smartSnap: formatMessage('stage.smartSnap', messages.smartSnap),
    fitSelection: formatMessage('stage.fitSelection', messages.fitSelection),
    zoomIn: formatMessage('stage.zoomIn', messages.zoomIn),
    zoomOut: formatMessage('stage.zoomOut', messages.zoomOut),
    zoomReset: formatMessage('stage.zoomReset', messages.zoomReset),
    loadingLayoutEngine: formatMessage(
      'stage.loadingLayoutEngine',
      messages.loadingLayoutEngine,
    ),
    assetDropNoResolver: formatMessage(
      'stage.assetDropNoResolver',
      messages.assetDropNoResolver,
    ),
    assetDropAllFailed: (failed: number) => formatMessage(
      'stage.assetDropAllFailed',
      messages.assetDropAllFailed(failed),
      { failed },
    ),
    assetDropAdded: (added: number) => formatMessage(
      'stage.assetDropAdded',
      messages.assetDropAdded(added),
      { added },
    ),
    assetDropPartial: (added: number, failed: number) => formatMessage(
      'stage.assetDropPartial',
      messages.assetDropPartial(added, failed),
      { added, failed },
    ),
    assetDropCommand: (added: number) => formatMessage(
      'stage.assetDropCommand',
      messages.assetDropCommand(added),
      { added },
    ),
  }
}
