/** 编辑器内建文案的解析结果。 @internal */
export type EditorMessages = ReturnType<typeof getEditorMessages>

export function getEditorMessages(
  locale: ComposeLocale,
  formatMessage: FormatMessage = (_id, fallback) => fallback,
) {
  const current = messages[locale]
  const format = (id: string, fallback: string) =>
    formatMessage(`editor.${id}`, fallback)
  const withVariables = (
    id: string,
    fallback: string,
    variables: Readonly<Record<string, string | number>>,
  ) => formatMessage(`editor.${id}`, fallback, variables)
  return {
    settings: format('settings', current.settings),
    user: format('user', current.user),
    close: format('close', current.close),
    search: format('search', current.search),
    searchPlaceholder: format('searchPlaceholder', current.searchPlaceholder),
    appearance: format('appearance', current.appearance),
    language: format('language', current.language),
    shortcuts: format('shortcuts', current.shortcuts),
    dark: format('dark', current.dark),
    light: format('light', current.light),
    system: format('system', current.system),
    resetAll: format('resetAll', current.resetAll),
    capture: format('capture', current.capture),
    conflict: (action: string) => withVariables(
      'conflict',
      current.conflict(action),
      { action },
    ),
    clear: (action: string) => withVariables('clear', current.clear(action), { action }),
    restore: (action: string) => withVariables(
      'restore',
      current.restore(action),
      { action },
    ),
    edit: (action: string) => withVariables('edit', current.edit(action), { action }),
    disabled: format('disabled', current.disabled),
    save: format('save', current.save),
    discard: format('discard', current.discard),
    closeAsset: (name: string) => withVariables(
      'closeAsset',
      current.closeAsset(name),
      { name },
    ),
    unsavedAssetTitle: format('unsavedAssetTitle', current.unsavedAssetTitle),
    unsavedAssetQuestion: (name: string) => withVariables(
      'unsavedAssetQuestion',
      current.unsavedAssetQuestion(name),
      { name },
    ),
    readonly: format('readonly', current.readonly),
    readonlyItems: current.readonlyItems.map(([term, description], index) => [
      format(`readonlyItems.${index}.term`, term),
      format(`readonlyItems.${index}.description`, description),
    ] as const),
    workspace: Object.fromEntries(
      Object.entries(current.workspace).map(([key, fallback]) => [
        key,
        format(`workspace.${key}`, fallback),
      ]),
    ) as Record<keyof typeof current.workspace, string>,
    stageToolbar: Object.fromEntries(
      Object.entries(current.stageToolbar).map(([key, fallback]) => [
        key,
        format(`stageToolbar.${key}`, fallback),
      ]),
    ) as Record<keyof typeof current.stageToolbar, string>,
    pages: {
      createPage: format('pages.createPage', current.pages.createPage),
      createPageTitle: format('pages.createPageTitle', current.pages.createPageTitle),
      defaultPageName: format('pages.defaultPageName', current.pages.defaultPageName),
      setAsHomePage: format('pages.setAsHomePage', current.pages.setAsHomePage),
      openJsonConfig: format('pages.openJsonConfig', current.pages.openJsonConfig),
      homePageBadge: format('pages.homePageBadge', current.pages.homePageBadge),
      closePage: (name: string) => withVariables(
        'pages.closePage',
        current.pages.closePage(name),
        { name },
      ),
      unsavedPageTitle: format('pages.unsavedPageTitle', current.pages.unsavedPageTitle),
      saveFailed: format('pages.saveFailed', current.pages.saveFailed),
      conflictTitle: format('pages.conflictTitle', current.pages.conflictTitle),
      conflictQuestion: (name: string) => withVariables(
        'pages.conflictQuestion',
        current.pages.conflictQuestion(name),
        { name },
      ),
      overwrite: format('pages.overwrite', current.pages.overwrite),
      dirtyIndicator: format('pages.dirtyIndicator', current.pages.dirtyIndicator),
      readOnlySuffix: format('pages.readOnlySuffix', current.pages.readOnlySuffix),
      homePageMissing: format('pages.homePageMissing', current.pages.homePageMissing),
      savePage: format('pages.savePage', current.pages.savePage),
      pageEntry: format('pages.pageEntry', current.pages.pageEntry),
    },
    canvasSettings: {
      label: format('canvasSettings.label', current.canvasSettings.label),
      stepX: format('canvasSettings.stepX', current.canvasSettings.stepX),
      stepY: format('canvasSettings.stepY', current.canvasSettings.stepY),
      offsetX: format('canvasSettings.offsetX', current.canvasSettings.offsetX),
      offsetY: format('canvasSettings.offsetY', current.canvasSettings.offsetY),
      primaryLineEvery: format(
        'canvasSettings.primaryLineEvery',
        current.canvasSettings.primaryLineEvery,
      ),
      nodeSnap: format('canvasSettings.nodeSnap', current.canvasSettings.nodeSnap),
      guideSnap: format('canvasSettings.guideSnap', current.canvasSettings.guideSnap),
      clearGuides: (count: number) => withVariables(
        'canvasSettings.clearGuides',
        current.canvasSettings.clearGuides(count),
        { count },
      ),
      willClearGuides: format(
        'canvasSettings.willClearGuides',
        current.canvasSettings.willClearGuides,
      ),
      cancel: format('canvasSettings.cancel', current.canvasSettings.cancel),
      apply: format('canvasSettings.apply', current.canvasSettings.apply),
      invalid: format('canvasSettings.invalid', current.canvasSettings.invalid),
      rejected: format('canvasSettings.rejected', current.canvasSettings.rejected),
      configureTransaction: format(
        'canvasSettings.configureTransaction',
        current.canvasSettings.configureTransaction,
      ),
      configureAndClearTransaction: format(
        'canvasSettings.configureAndClearTransaction',
        current.canvasSettings.configureAndClearTransaction,
      ),
    },
    canvasInspector: Object.fromEntries(
      Object.entries(current.canvasInspector).map(([key, fallback]) => [
        key,
        format(`canvasInspector.${key}`, fallback),
      ]),
    ) as Record<keyof typeof current.canvasInspector, string>,
  }
}

export function getRequiredEditorMessage(
  locale: ComposeLocale,
  key: string,
) {
  const dictionary = messages[locale] as unknown as Record<string, unknown>
  if (!(key in dictionary)) {
    throw new Error(`Missing editor translation: ${locale}.${key}`)
  }
  return dictionary[key]
}

export function getEditorShortcutActionLabel(
  locale: ComposeLocale,
  action: ComposeEditorShortcutAction,
  formatMessage: FormatMessage = (_id, fallback) => fallback,
) {
  return formatMessage(
    `editor.shortcut.${action}`,
    actionLabels[locale][action],
  )
}
